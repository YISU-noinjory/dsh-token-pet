/**
 * 随机抽一卦。
 *
 * `random` 可注入，让抽取逻辑能脱离随机性单独测试。
 *
 * @param random - 返回 [0, 1) 的函数，默认 `Math.random`。
 * @returns 抽中的卦。
 */
export function pickRandomHexagram(random: () => number = Math.random): Hexagram {
  // 用 floor 而不是 round：round 会让首尾两卦的概率只有中间的一半。
  const index = Math.min(HEXAGRAMS.length - 1, Math.floor(random() * HEXAGRAMS.length))
  return HEXAGRAMS[index] as Hexagram
}
